def get_translation(key: str, lang: Optional[str] = "en", default: Optional[str] = None) -> str:
    """Retrieve translated string with fallback to English then key."""
    if not lang or lang not in TRANSLATIONS:
        lang = "en"
    
    target_dict = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    if key in target_dict:
        return target_dict[key]
    
    # Fallback to English
    if key in TRANSLATIONS["en"]:
        return TRANSLATIONS["en"][key]
        
    return default if default is not None else key
